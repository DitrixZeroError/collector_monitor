# Строка целиком похожа на дату (возможно, со временем)
DATE_PATTERN = re.compile(r"^\s*\d{1,4}[./\-]\d{1,2}[./\-]\d{1,4}(\s+\d{1,2}:\d{2}(:\d{2})?)?\s*$")
# Строка целиком похожа на число — целое или дробное
NUMBER_PATTERN = re.compile(r"^\s*-?\d+(?:[.,]\d+)?\s*$")


def normalize_value(value):
    """Убирает пробелы по краям и приводит разные написания к одному."""
    text = str(value).strip()
    return NORM_VALUES.get(text, text)


@lru_cache(maxsize=4096)
def classify_pair(sensor_type, value):
    """
    Определяет уровень события для пары «тип датчика — значение».

    Возвращает кортеж (уровень, число). Число заполнено только для
    датчиков температуры и газа, в остальных случаях — NaN.

    Пар «тип — значение» немного, поэтому результат кэшируется (lru_cache):
    каждую пару разбираем один раз, как и в ноутбуке.
    """
    if sensor_type is None or value is None:
        return LEVEL_DROP, math.nan

    text = normalize_value(value)
    number = float(text.replace(",", ".")) if NUMBER_PATTERN.match(text) else math.nan
    has_number = not math.isnan(number)

    # --- Датчик температуры с числовым показанием ---
    if sensor_type == "Датчик температуры" and has_number:
        if number in TEMP_FAULT_CODES or number > 150 or number <= -60:
            return LEVEL_DROP, math.nan
        if number >= TEMP_FIRE_C:
            return LEVEL_FIRE, number
        if number >= TEMP_RISK_C:
            return LEVEL_RISK, number
        return LEVEL_OK, number

    # --- Газовый датчик с числовым показанием ---
    if sensor_type == "Газовый датчик" and has_number:
        if number < 0 or number >= GAS_IMPLAUSIBLE:
            return LEVEL_DROP, math.nan
        if number >= GAS_ALARM:
            return LEVEL_GAS, number
        if number >= GAS_RISK:
            return LEVEL_RISK, number
        return LEVEL_OK, number

    # --- «Состояние охраны» иногда присылает дату вместо состояния ---
    if sensor_type == "Состояние охраны" and DATE_PATTERN.match(text):
        is_empty_date = text.startswith("01.01.1970")
        return (LEVEL_DROP if is_empty_date else LEVEL_OK), math.nan

    # --- Цифры там, где их быть не должно, и игнорируемые типы ---
    if sensor_type in TYPES_NO_DIGITS and re.search(r"\d", text):
        return LEVEL_DROP, math.nan
    if sensor_type in IGNORE_TYPES:
        return LEVEL_DROP, math.nan

    # --- Всё остальное — по таблице правил. Неизвестная пара отбрасывается ---
    level = RULES.get(sensor_type, {}).get(text, LEVEL_DROP)
    return level, math.nan


def precursor_name(sensor_type, value):
    """Имя признака-предвестника (pre_*) для пары или None."""
    return PRECURSORS.get((sensor_type, normalize_value(value)))


def type_short_name(sensor_type):
    """Короткое имя типа датчика для имён признаков (smoke, heat…)."""
    return TYPE_SHORT.get(sensor_type, UNKNOWN_TYPE_SHORT)


def fire_detector_state(value):
    """
    Состояние пожарного извещателя по значению:
        1  — «слепой» (неисправен, отключён, нет данных);
        0  — рабочий;
        None — значение ничего не говорит о состоянии.
    """
    text = normalize_value(value)
    if text in FIRE_DETECTOR_FAULT_VALUES:
        return 1
    if text in FIRE_DETECTOR_WORKING_VALUES:
        return 0
    return None


