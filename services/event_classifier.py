# Уровень события -> состояние, которое видит диспетчер
_STATUS_BY_LEVEL = {
    LEVEL_FIRE: "alarm",
    LEVEL_GAS: "alarm",
    LEVEL_RISK: "warning",
    LEVEL_PRESENCE: "presence",
    LEVEL_NO_DATA: "nodata",
    LEVEL_OK: "ok",
    LEVEL_DROP: "ok",
}


def describe_value_status(sensor_type, value, is_alarm_flag):
    """
    Оценивает показание для отображения диспетчеру.

    Возвращает: "alarm" (тревога), "warning" (внимание), "presence"
    (люди или работы на объекте), "nodata" (нет данных), "ok" (норма).
    Флаг «тревожное» из журнала всегда даёт «тревогу».
    """
    if is_alarm_flag:
        return "alarm"
    level, _number = classify_pair(sensor_type, value)
    return _STATUS_BY_LEVEL.get(level, "ok")
